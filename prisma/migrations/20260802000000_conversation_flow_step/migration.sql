-- Conversations.flow_step 추가.
--
-- 대화 흐름 단계를 "사용자 발화 2턴마다" 넘기고 있었는데, 턴 수는 진행도의 조잡한 대리 지표다.
-- 사용자가 아직 그 단계를 해내지 못했는데도 다음 단계로 넘어가 버리고, 반대로 빨리 해낸
-- 사용자는 불필요하게 같은 단계에 묶인다.
--
-- 이제 각 단계에 통과 조건(advanceWhen)을 두고, 사용자 발화가 그 조건과 의미상 맞을 때만
-- 단계를 올린다. 그 진행 상태를 여기에 저장한다.
-- 판정에 쓰는 임베딩은 매 턴 상황 규칙 매칭용으로 이미 만드는 벡터를 재사용하므로
-- 임베딩 API 호출은 늘지 않는다.
--
-- 기본값 0이라 기존 대화는 첫 단계부터 시작한다.

-- AlterTable
ALTER TABLE `Conversations` ADD COLUMN `flow_step` INTEGER NOT NULL DEFAULT 0;
